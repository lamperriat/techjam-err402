  const CATALOGS = Object.freeze({ en: Object.freeze(en), "zh-Hans": Object.freeze(zh) });

  function normalize(locale) {
    return locale === "zh" || locale === "zh-CN" || locale === "zh-Hans" ? "zh-Hans" : "en";
  }

  function translate(locale, key, variables = {}) {
    const normalized = normalize(locale);
    const template = CATALOGS[normalized][key] ?? CATALOGS.en[key] ?? key;
    return String(template).replace(/\{([a-zA-Z0-9_]+)\}/g, (_, name) => String(variables[name] ?? `{${name}}`));
  }

  function artifact(locale, key, fallback) {
    return normalize(locale) === "zh-Hans" ? (ARTIFACT_ZH[key] ?? fallback) : fallback;
  }

  function loadLocale(storage) {
    try {
      const target = storage === undefined ? root.localStorage : storage;
      return normalize(target?.getItem(STORAGE_KEY));
    } catch { return DEFAULT_LOCALE; }
  }

  function saveLocale(locale, storage) {
    const normalized = normalize(locale);
    try {
      const target = storage === undefined ? root.localStorage : storage;
      target?.setItem(STORAGE_KEY, normalized);
    } catch { /* storage can be unavailable */ }
    return normalized;
  }

  const api = Object.freeze({ STORAGE_KEY, DEFAULT_LOCALE, SUPPORTED_LOCALES, CATALOGS, normalize, translate, artifact, loadLocale, saveLocale });
